export const ModePill = ({ mode, active, disabled, loading, onClick, className }: ModePillProps) => {
  const modeConfig = ANC_MODES.find(m => m.value === mode);
  const Icon = modeConfig?.icon ? modeIcons[modeConfig.icon] : null;
  
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled || loading}
      aria-pressed={active}
      aria-disabled={disabled || loading}
      aria-label={modeConfig?.label || mode}
      className={twMerge(
        'inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-sm font-medium transition-all duration-150 ease-out',
        'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent focus-visible:ring-offset-2',
        active
          ? 'bg-accent text-on-accent shadow-sm'
          : 'bg-surface text-text border border-border hover:bg-surface/80',
        disabled && 'opacity-50 cursor-not-allowed',
        loading && 'cursor-wait',
        className
      )}
    >
      {loading ? (
        <svg className="animate-spin h-4 w-4" viewBox="0 0 24 24" aria-hidden="true">
          <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" fill="none" />
          <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z" />
        </svg>
      ) : (
        Icon
      )}
      <span>{modeConfig?.label || mode}</span>
    </button>
  );
};

